static const unsigned char *ffdhe_p(int group, intptr_t *plen, int *privbits)
{
  switch (group) {
    case RKTCRYPTO_FFDHE2048: *plen = 256; *privbits = 225; return FFDHE2048_P;
    case RKTCRYPTO_FFDHE3072: *plen = 384; *privbits = 275; return FFDHE3072_P;
    case RKTCRYPTO_FFDHE4096: *plen = 512; *privbits = 325; return FFDHE4096_P;
    default: *plen = 0; *privbits = 0; return 0;
  }
}

intptr_t rktcrypto_ffdhe_size(int group)
{
  intptr_t plen; int pb;
  ffdhe_p(group, &plen, &pb);
  return plen;
}

int rktcrypto_ffdhe_keygen(int group, unsigned char *priv_out, intptr_t *privlen,
                           unsigned char *pub_out)
{
  intptr_t plen; int privbits;
  const unsigned char *pb = ffdhe_p(group, &plen, &privbits);
  BN P, X, G, Y;
  intptr_t nb = (privbits + 7) / 8;
  unsigned char buf[64];
  int tries;
  if (!pb) return 0;
  for (tries = 0; ; tries++) {
    if (tries == 100) return 0;
    if (!rktcrypto_random_bytes(buf, 0, nb)) return 0;
    if (privbits % 8) buf[0] &= (unsigned char)(0xff >> (8 - privbits % 8));
    bn_from_be(&X, buf, (int)nb);
    if (!bn_is_zero(&X)) break;
  }
  bn_from_be(&P, pb, (int)plen);
  bn_set_u64(&G, 2);
  bn_modexp(&Y, &G, &X, &P);
  memcpy(priv_out, buf, nb);
  *privlen = nb;
  bn_to_be(pub_out, (int)plen, &Y);
  return 1;
}

int rktcrypto_ffdhe_derive(int group, const unsigned char *priv, intptr_t privlen,
                           const unsigned char *peer, intptr_t peerlen,
                           unsigned char *out)
{
  intptr_t plen; int privbits;
  const unsigned char *pb = ffdhe_p(group, &plen, &privbits);
  BN P, X, T, S, Pm1, One;
  if (!pb) return 0;
  bn_from_be(&P, pb, (int)plen);
  bn_from_be(&T, peer, (int)peerlen);
  bn_set_u64(&One, 1);
  bn_sub(&Pm1, &P, &One);
  /* peer must be in [2, p-2] */
  if (bn_is_zero(&T)) return 0;
  if (bn_cmp(&T, &One) <= 0) return 0;
  if (bn_cmp(&T, &Pm1) >= 0) return 0;
  bn_from_be(&X, priv, (int)privlen);
  if (bn_is_zero(&X)) return 0;
  bn_modexp(&S, &T, &X, &P);
  /* reject degenerate shared secrets */
  if (bn_is_zero(&S) || bn_cmp(&S, &One) == 0 || bn_cmp(&S, &Pm1) == 0) return 0;
  bn_to_be(out, (int)plen, &S);
  return 1;
}
