/* ============================ Ed448 ============================ */
static int test_ed448(void) {
  int ok = 1, r;
  unsigned char pk[57], sig[114];
  unsigned char tmsg[MSG_LEN], tsig[114];

  /* 1. pubkey matches KAT */
  r = rktcrypto_ed448_pubkey(pk, ED448_SK);
  if (r != 1 || memcmp(pk, ED448_PK, 57) != 0) { printf("  ed448 pubkey mismatch (r=%d)\n", r); ok = 0; }

  /* 2. INTEROP: our verify accepts python's signature */
  if (rktcrypto_ed448_verify(ED448_SIG, MSG, MSG_LEN, ED448_PK) != 1) {
    printf("  ed448 verify REJECTED a valid python signature\n"); ok = 0; }

  /* 3. roundtrip: our sign -> our verify (Ed448 is deterministic, so also
        cross-check the bytes equal python's KAT signature) */
  r = rktcrypto_ed448_sign(sig, MSG, MSG_LEN, ED448_SK, ED448_PK);
  if (r != 1 || rktcrypto_ed448_verify(sig, MSG, MSG_LEN, ED448_PK) != 1) {
    printf("  ed448 sign/verify roundtrip failed (sign r=%d)\n", r); ok = 0; }
  if (memcmp(sig, ED448_SIG, 114) != 0) {
    printf("  ed448 deterministic signature != python KAT signature\n"); ok = 0; }

  /* 4. NEGATIVE: tampered message and mangled signature rejected */
  memcpy(tmsg, MSG, MSG_LEN); tmsg[0] ^= 0x01;
  if (rktcrypto_ed448_verify(ED448_SIG, tmsg, MSG_LEN, ED448_PK) != 0) {
    printf("  ed448 verify ACCEPTED a tampered message\n"); ok = 0; }
  memcpy(tsig, ED448_SIG, 114); tsig[10] ^= 0x01;
  if (rktcrypto_ed448_verify(tsig, MSG, MSG_LEN, ED448_PK) != 0) {
    printf("  ed448 verify ACCEPTED a mangled signature\n"); ok = 0; }

  report("Ed448", ok);
  return ok;
}

