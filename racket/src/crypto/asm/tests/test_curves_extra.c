/* ============================ P-384 ============================ */
static int test_p384(void) {
  int ok = 1, r;
  unsigned char pub[97], sh[48], sig[96];
  unsigned char tmsg[MSG_LEN], tsig[96];

  /* 1. pubkey/keygen matches KAT */
  r = rktcrypto_p384_pubkey(pub, P384_PRIV);
  if (r != 1 || memcmp(pub, P384_PUB, 97) != 0) { printf("  p384 pubkey mismatch (r=%d)\n", r); ok = 0; }

  /* 2. INTEROP: our verify accepts python's signature */
  if (rktcrypto_p384_ecdsa_verify(P384_SIG, MSG, MSG_LEN, P384_PUB) != 1) {
    printf("  p384 verify REJECTED a valid python signature\n"); ok = 0; }
  /* 2b. INTEROP verify_h with the precomputed SHA-384 digest */
  if (rktcrypto_p384_ecdsa_verify_h(P384_SIG, P384_HASH, 48, P384_PUB) != 1) {
    printf("  p384 verify_h REJECTED a valid python signature\n"); ok = 0; }
  /* 2c. INTEROP ECDH: our (priv * peerpub) == python shared */
  r = rktcrypto_p384_ecdh(sh, P384_PRIV, P384_PEERPUB);
  if (r != 1 || memcmp(sh, P384_SHARED, 48) != 0) { printf("  p384 ecdh mismatch (r=%d)\n", r); ok = 0; }

  /* 3. roundtrip: our sign -> our verify */
  r = rktcrypto_p384_ecdsa_sign(sig, MSG, MSG_LEN, P384_PRIV);
  if (r != 1 || rktcrypto_p384_ecdsa_verify(sig, MSG, MSG_LEN, P384_PUB) != 1) {
    printf("  p384 sign/verify roundtrip failed (sign r=%d)\n", r); ok = 0; }

  /* 4. NEGATIVE: tampered message must be rejected */
  memcpy(tmsg, MSG, MSG_LEN); tmsg[0] ^= 0x01;
  if (rktcrypto_p384_ecdsa_verify(P384_SIG, tmsg, MSG_LEN, P384_PUB) != 0) {
    printf("  p384 verify ACCEPTED a tampered message\n"); ok = 0; }
  /* 4b. NEGATIVE: mangled signature must be rejected */
  memcpy(tsig, P384_SIG, 96); tsig[10] ^= 0x01;
  if (rktcrypto_p384_ecdsa_verify(tsig, MSG, MSG_LEN, P384_PUB) != 0) {
    printf("  p384 verify ACCEPTED a mangled signature\n"); ok = 0; }
  /* 4c. NEGATIVE via verify_h: tampered digest must be rejected */
  { unsigned char th[48]; memcpy(th, P384_HASH, 48); th[0] ^= 0x01;
    if (rktcrypto_p384_ecdsa_verify_h(P384_SIG, th, 48, P384_PUB) != 0) {
      printf("  p384 verify_h ACCEPTED a tampered digest\n"); ok = 0; } }

  report("P-384", ok);
  return ok;
}

